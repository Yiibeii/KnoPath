export type Locale = keyof typeof messages
export type TranslationKey = keyof (typeof messages)['zh']

export function t(locale: string | undefined, key: TranslationKey, ...args: (string | number)[]): string {
  const lang = locale === 'en' ? 'en' : 'zh'
  let text: string = messages[lang][key] ?? messages['zh'][key] ?? key
  args.forEach((arg, i) => {
    text = text.replace(`{${i}}`, String(arg))
  })
  return text
}
